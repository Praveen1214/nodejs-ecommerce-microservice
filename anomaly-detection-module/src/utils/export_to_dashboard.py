"""
Export ML Results to Dashboard
Converts test results to dashboard-compatible format
"""

import json
import os
import glob

def export_curves_to_dashboard():
    """Export curve data to dashboard data file"""

    dashboard_path = "/root/Project/model-insights-dashboard/src/data"
    curve_data = {}

    # Process each version
    for version in ['v1', 'v2', 'v3']:
        version_dir = f"/root/Project/ML-based-Threat-aware-Auto-scaling-in-Kubernetes/results/test_results/{version}"

        if not os.path.exists(version_dir):
            continue

        curve_data[version] = {}

        # Find all curve files
        curve_files = glob.glob(os.path.join(version_dir, "*_curves.json"))

        for curve_file in curve_files:
            model_name = os.path.basename(curve_file).replace('_curves.json', '')

            with open(curve_file, 'r') as f:
                curves = json.load(f)
                curve_data[version][model_name] = curves

            print(f"✓ Loaded curves for {version}/{model_name}")

    # Save to dashboard
    output_file = os.path.join(dashboard_path, "curveData.ts")

    with open(output_file, 'w') as f:
        f.write("// Auto-generated curve data from ML models\n")
        f.write("// Generated by export_to_dashboard.py\n\n")
        f.write("export interface CurveData {\n")
        f.write("  roc: {\n")
        f.write("    fpr: number[];\n")
        f.write("    tpr: number[];\n")
        f.write("    auc: number;\n")
        f.write("  };\n")
        f.write("  pr: {\n")
        f.write("    precision: number[];\n")
        f.write("    recall: number[];\n")
        f.write("    auc: number;\n")
        f.write("  };\n")
        f.write("}\n\n")
        f.write("export const curveData: Record<string, Record<string, CurveData>> = ")
        f.write(json.dumps(curve_data, indent=2))
        f.write(";\n")

    print(f"\n✓ Curve data exported to: {output_file}")
    return curve_data


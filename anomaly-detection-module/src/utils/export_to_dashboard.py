    curve_data = export_curves_to_dashboard()

    # Export training history
    print("\n[2/2] Exporting training history...")
    history_data = export_training_history()

    print("\n" + "=" * 70)
    print("✅ EXPORT COMPLETE!")
    print("=" * 70)

    print("\nExported data:")
